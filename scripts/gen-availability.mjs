#!/usr/bin/env node
// @ts-check
/**
 * scripts/gen-availability.mjs — render the shared availability contract from
 * config/availability.json.
 *
 * The host, the Gateway and the Blender add-on must agree on the failure stages,
 * the four-question envelope fields, the fallback kinds and the per-stage
 * diagnostic budgets. This generator renders all three from the single JSON
 * source:
 *   - src/contracts/availability.generated.ts
 *   - runtime/core/availability-schema.generated.ts
 *   - runtime/py/core/availability_schema.py
 *
 * scripts/check-availability-schema.mjs (npm run check:availability) fails when
 * a generated file is missing, stale, or hand-edited.
 */
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
export const DEFAULT_ROOT = path.resolve(HERE, '..')
export const SCHEMA_FILE = 'config/availability.json'
export const GENERATED_FILES = [
  'src/contracts/availability.generated.ts',
  'runtime/core/availability-schema.generated.ts',
  'extension/dsh_blender_bridge/availability_schema.py',
]

const EXPECTED_STAGES = [
  'config',
  'session',
  'spawn',
  'transport',
  'handshake',
  'addon',
  'bpy',
  'queue',
  'render',
]
const EXPECTED_REQUIRED_FIELDS = ['stage', 'root_cause', 'fix', 'fallback', 'evidence']
const EXPECTED_FALLBACK_KINDS = ['unavailable', 'degraded']
const EXPECTED_BUDGET_CEILINGS = {
  config: 100,
  session: 100,
  spawn: 250,
  transport: 3000,
  handshake: 3000,
  addon: 3000,
  bpy: 3000,
  queue: 3000,
  render: 3000,
}

const fail = (message) => {
  console.error('gen-availability: ' + message)
  process.exit(1)
}
const isPositiveInteger = (value) => Number.isInteger(value) && value > 0

function sameOrder(left, right) {
  return Array.isArray(left) && left.join(',') === right.join(',')
}

export function validateAvailabilitySchema(config) {
  const failures = []
  if (!config || typeof config !== 'object') return ['top-level value must be an object']
  if (config.version !== 1) failures.push('version must be 1')
  if (!sameOrder(config.generated, GENERATED_FILES))
    failures.push('generated must list ' + GENERATED_FILES.join(' + '))
  if (!sameOrder(config.stages, EXPECTED_STAGES))
    failures.push('stages must be exactly ' + EXPECTED_STAGES.join(', '))
  if (!sameOrder(config.requiredFields, EXPECTED_REQUIRED_FIELDS))
    failures.push('requiredFields must be exactly ' + EXPECTED_REQUIRED_FIELDS.join(', '))
  if (!sameOrder(config.fallbackKinds, EXPECTED_FALLBACK_KINDS))
    failures.push('fallbackKinds must be exactly ' + EXPECTED_FALLBACK_KINDS.join(', '))
  const budgets = config.budgetsMs
  if (!budgets || typeof budgets !== 'object' || Array.isArray(budgets)) {
    failures.push('budgetsMs must be an object')
  } else {
    const keys = Object.keys(budgets)
    if (keys.join(',') !== EXPECTED_STAGES.join(','))
      failures.push('budgetsMs keys must match stages in order')
    for (const stage of EXPECTED_STAGES) {
      const value = budgets[stage]
      if (!isPositiveInteger(value)) {
        failures.push('budgetsMs.' + stage + ' must be a positive integer')
        continue
      }
      if (value > EXPECTED_BUDGET_CEILINGS[stage])
        failures.push(
          'budgetsMs.' + stage + ' must stay <= ' + String(EXPECTED_BUDGET_CEILINGS[stage]),
        )
    }
  }
  return failures
}

function header(hash) {
  return [
    'AUTO-GENERATED FILE - generated by scripts/gen-availability.mjs; do not edit.',
    'Source: config/availability.json',
    'Regenerate: node scripts/gen-availability.mjs',
    'source-sha256: ' + hash,
  ]
}

function tsHeader(hash) {
  return header(hash)
    .map((line) => '// ' + line)
    .join('\n')
}

function renderTs(config, hash) {
  const stages = config.stages.map((stage) => "'" + stage + "'").join(', ')
  const required = config.requiredFields.map((field) => "'" + field + "'").join(', ')
  const fallbacks = config.fallbackKinds.map((kind) => "'" + kind + "'").join(', ')
  const budgets = config.stages
    .map((stage) => '  ' + stage + ': ' + String(config.budgetsMs[stage]) + ',')
    .join('\n')
  return [
    tsHeader(hash),
    '',
    'export const AVAILABILITY_SCHEMA_VERSION = ' + config.version,
    'export const AVAILABILITY_STAGES = [' + stages + '] as const',
    'export type AvailabilityStage = (typeof AVAILABILITY_STAGES)[number]',
    'export const AVAILABILITY_REQUIRED_FIELDS = [' + required + '] as const',
    'export type AvailabilityRequiredField = (typeof AVAILABILITY_REQUIRED_FIELDS)[number]',
    'export const AVAILABILITY_FALLBACK_KINDS = [' + fallbacks + '] as const',
    'export type AvailabilityFallbackKind = (typeof AVAILABILITY_FALLBACK_KINDS)[number]',
    'export const AVAILABILITY_BUDGETS_MS = {',
    budgets,
    '} as const satisfies Record<AvailabilityStage, number>',
    '',
  ].join('\n')
}

function renderPy(config, hash) {
  const quote = (value) => JSON.stringify(value)
  const tuple = (values) =>
    '(' + values.map(quote).join(', ') + (values.length === 1 ? ',' : '') + ')'
  const stages = tuple(config.stages)
  const required = tuple(config.requiredFields)
  const fallbacks = tuple(config.fallbackKinds)
  const budgets = config.stages
    .map((stage) => '    ' + quote(stage) + ': ' + String(config.budgetsMs[stage]) + ',')
    .join('\n')
  return [
    '"""Availability failure contract generated from config/availability.json.',
    '',
    ...header(hash).map((line) => ' ' + line),
    '"""',
    '',
    'AVAILABILITY_SCHEMA_VERSION = ' + config.version,
    'AVAILABILITY_STAGES = ' + stages,
    'AVAILABILITY_REQUIRED_FIELDS = ' + required,
    'AVAILABILITY_FALLBACK_KINDS = ' + fallbacks,
    'AVAILABILITY_BUDGETS_MS = {',
    budgets,
    '}',
    '',
  ].join('\n')
}

export function generateAvailabilitySchema(root = DEFAULT_ROOT) {
  const sourcePath = path.join(root, SCHEMA_FILE)
  const source = fs.readFileSync(sourcePath, 'utf8')
  let config
  try {
    config = JSON.parse(source)
  } catch (error) {
    throw new Error(
      SCHEMA_FILE +
        ' is not valid JSON: ' +
        (error instanceof Error ? error.message : String(error)),
      { cause: error },
    )
  }
  const failures = validateAvailabilitySchema(config)
  if (failures.length) throw new Error('invalid ' + SCHEMA_FILE + ': ' + failures.join('; '))
  const hash = crypto.createHash('sha256').update(source).digest('hex')
  const contents = [renderTs(config, hash), renderTs(config, hash), renderPy(config, hash)]
  return {
    hash,
    config,
    files: GENERATED_FILES.map((file, index) => ({ file, content: contents[index] })),
  }
}

function main() {
  const args = process.argv.slice(2)
  let check = false
  for (const arg of args) {
    if (arg === '--check') check = true
    else fail('unknown argument ' + arg)
  }
  const generated = generateAvailabilitySchema()
  let stale = 0
  for (const file of generated.files) {
    const target = path.join(DEFAULT_ROOT, file.file)
    if (check) {
      let actual
      try {
        actual = fs.readFileSync(target, 'utf8')
      } catch {
        console.error('gen-availability: ' + file.file + ' is missing')
        stale += 1
        continue
      }
      if (actual !== file.content) {
        console.error('gen-availability: ' + file.file + ' is stale')
        stale += 1
      }
    } else {
      fs.mkdirSync(path.dirname(target), { recursive: true })
      fs.writeFileSync(target, file.content)
      console.log('wrote ' + file.file)
    }
  }
  if (check && stale) process.exit(1)
  if (check) console.log('gen-availability: OK (sha256 ' + generated.hash.slice(0, 12) + ')')
}

const MAIN = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (MAIN) main()

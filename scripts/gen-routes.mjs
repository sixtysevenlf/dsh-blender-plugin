#!/usr/bin/env node
// @ts-check
/**
 * scripts/gen-routes.mjs — generate the GUI dispatch table from config/routing.json .
 *
 * config/routing.json is the single source of truth for plan/EXT GUI routing. This
 * script renders:
 *   - runtime/core/dispatcher/routes.generated.ts (GUI addon dispatch table)
 *
 * The host-side worker mapping table was removed in 3.1 together with the worker
 * plan channel; `blender_run` submits scripts through the job queue instead.
 * The output carries the sha256 of the source and the regeneration command.
 * `node scripts/check-routes.mjs` (npm run check:routes) fails when the checked-in
 * generated file no longer matches the source (or was hand-edited).
 */
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import * as prettier from 'prettier'

const HERE = path.dirname(fileURLToPath(import.meta.url))
export const DEFAULT_ROOT = path.resolve(HERE, '..')
export const ROUTING_FILE = 'config/routing.json'
export const GENERATED_FILES = ['runtime/core/dispatcher/routes.generated.ts']

const SIDES = new Set(['gui'])
const GROUPS = ['main', 'module', 'ext']
const KINDS = ['dispatch', 'qc-render', 'montage', 'motion', 'deliver', 'view', 'render']
const MATCHES = new Set(['prefix', 'exact'])
const API_PATTERN = /^dsh_[a-z0-9_]+_api$/
const ENSURE_PATTERN = /^ensure[A-Za-z0-9]+$/

const fail = (message) => {
  console.error('gen-routes: ' + message)
  process.exit(1)
}

const isNonEmptyString = (value) => typeof value === 'string' && value.length > 0

function header(hash) {
  return [
    '// AUTO-GENERATED FILE — generated by scripts/gen-routes.mjs; do not edit.',
    '// Source: config/routing.json',
    '// Regenerate: node scripts/gen-routes.mjs',
    '// source-sha256: ' + hash,
  ].join('\n')
}

export function validateRouting(config) {
  const failures = []
  if (!config || typeof config !== 'object') return ['top-level value must be an object']
  if (config.version !== 1) failures.push('version must be 1')
  if (!Array.isArray(config.generated) || config.generated.join(',') !== GENERATED_FILES.join(','))
    failures.push('generated must list ' + GENERATED_FILES.join(' + '))
  if (
    !Array.isArray(config.hostSideFamilies) ||
    config.hostSideFamilies.some((family) => !isNonEmptyString(family))
  )
    failures.push('hostSideFamilies must be an array of non-empty strings')
  const hostSide = new Set(Array.isArray(config.hostSideFamilies) ? config.hostSideFamilies : [])
  const routes = Array.isArray(config.routes) ? config.routes : []
  if (routes.length === 0) failures.push('routes must be a non-empty array')
  const ids = new Set()
  routes.forEach((row, index) => {
    const at = 'routes[' + index + ']'
    if (!row || typeof row !== 'object') {
      failures.push(at + ' must be an object')
      return
    }
    const add = (message) => failures.push(at + ' (' + String(row.id || '?') + '): ' + message)
    if (!isNonEmptyString(row.id)) add('id must be a non-empty string')
    else if (ids.has(row.id)) add('duplicate id')
    else ids.add(row.id)
    if (!SIDES.has(row.side)) add('side must be gui')
    if (!isNonEmptyString(row.family)) add('family must be a non-empty string')
    else if (hostSide.has(row.family))
      add('family ' + row.family + ' is declared host-side and cannot be routed')
    if (!isNonEmptyString(row.api) || !API_PATTERN.test(row.api))
      add('api must match dsh_<name>_api')
    if (!MATCHES.has(row.match)) add('match must be prefix|exact')
    if (!Number.isInteger(row.strip) || row.strip < 0) add('strip must be a non-negative integer')
    if (row.match === 'exact') {
      if (!isNonEmptyString(row.op)) add('exact rows need a non-empty op')
    } else if (typeof row.prefix !== 'string') {
      add('prefix rows need a prefix string')
    }
    if (GROUPS.indexOf(row.group) < 0) add('group must be main|module|ext')
    if (KINDS.indexOf(row.kind) < 0) add('kind must be one of ' + KINDS.join('|'))
    if (!isNonEmptyString(row.ensure) || !ENSURE_PATTERN.test(row.ensure))
      add('ensure must look like ensureXxx')
    if (!Number.isInteger(row.timeoutMs) || row.timeoutMs <= 0)
      add('timeoutMs must be a positive integer')
    if (row.kind === 'qc-render' && !isNonEmptyString(row.preload))
      add('qc-render rows need the worker preload chunk list')
    if (row.preload !== undefined && !isNonEmptyString(row.preload))
      add('preload must be a non-empty string when present')
    if (row.sub !== undefined && !isNonEmptyString(row.sub))
      add('sub must be a non-empty string when present')
    if (row.subAliases !== undefined) {
      if (!row.subAliases || typeof row.subAliases !== 'object' || Array.isArray(row.subAliases)) {
        add('subAliases must be an object')
      } else {
        for (const [key, value] of Object.entries(row.subAliases)) {
          if (!isNonEmptyString(key) || !isNonEmptyString(value))
            add('subAliases entries must map non-empty strings to non-empty strings')
        }
      }
    }
  })
  const guiRows = routes
  for (const group of GROUPS) {
    if (!guiRows.some((row) => row.group === group))
      failures.push('GUI group ' + group + ' has no routes')
  }
  const lastGui = guiRows[guiRows.length - 1]
  if (!lastGui || lastGui.prefix !== '')
    failures.push('the last GUI route must be the empty-prefix contract catch-all')
  return failures
}

function guiRowLiteral(row) {
  return (
    '{ ' +
    [
      'id: ' + JSON.stringify(row.id),
      'kind: ' + JSON.stringify(row.kind),
      'match: ' + JSON.stringify(row.match),
      'op: ' + (row.match === 'exact' ? JSON.stringify(row.op) : 'null'),
      'prefix: ' + JSON.stringify(row.prefix === undefined ? '' : row.prefix),
      'strip: ' + String(row.strip),
      'api: ' + JSON.stringify(row.api),
      'ensure: ' + JSON.stringify(row.ensure),
      'timeoutMs: ' + String(row.timeoutMs),
      'sub: ' + (row.sub === undefined ? 'null' : JSON.stringify(row.sub)),
      'preload: ' + (row.preload === undefined ? 'null' : JSON.stringify(row.preload)),
      'subAliases: ' + JSON.stringify(row.subAliases || {}),
    ].join(', ') +
    ' }'
  )
}

function renderGui(config, hash) {
  const guiRows = config.routes
  const ensureNames = [...new Set(guiRows.map((row) => row.ensure))].sort()
  const groupArray = (name, group) => [
    'export const ' + name + ': readonly GuiRoute[] = [',
    ...guiRows.filter((row) => row.group === group).map((row) => '  ' + guiRowLiteral(row) + ','),
    ']',
  ]
  return [
    header(hash),
    '',
    'export type GuiRouteKind = ' + KINDS.map((kind) => JSON.stringify(kind)).join(' | '),
    '',
    'export type EnsureName =',
    ensureNames.map((name) => '  | ' + JSON.stringify(name)).join('\n'),
    '',
    'export interface GuiRoute {',
    '  readonly id: string',
    '  readonly kind: GuiRouteKind',
    "  readonly match: 'prefix' | 'exact'",
    '  readonly op: string | null',
    '  readonly prefix: string',
    '  readonly strip: number',
    '  readonly api: string',
    '  readonly ensure: EnsureName',
    '  readonly timeoutMs: number',
    '  readonly sub: string | null',
    '  readonly preload: string | null',
    '  readonly subAliases: Readonly<Record<string, string>>',
    '}',
    '',
    ...groupArray('MAIN_ROUTES', 'main'),
    '',
    ...groupArray('MODULE_ROUTES', 'module'),
    '',
    ...groupArray('EXT_ROUTES', 'ext'),
  ].join('\n')
}

async function prettierOptions(root) {
  const configPath = path.join(root, '.prettierrc.json')
  try {
    return JSON.parse(fs.readFileSync(configPath, 'utf8'))
  } catch {
    return {}
  }
}

export async function generateRoutes(root = DEFAULT_ROOT) {
  const routingPath = path.join(root, ROUTING_FILE)
  let source
  try {
    source = fs.readFileSync(routingPath, 'utf8')
  } catch (error) {
    throw new Error(
      'cannot read ' + ROUTING_FILE + ': ' + String(error && error.message ? error.message : error),
      { cause: error },
    )
  }
  let config
  try {
    config = JSON.parse(source)
  } catch (error) {
    throw new Error(
      ROUTING_FILE +
        ' is not valid JSON: ' +
        String(error && error.message ? error.message : error),
      { cause: error },
    )
  }
  const failures = validateRouting(config)
  if (failures.length) throw new Error(ROUTING_FILE + ' is invalid:\n- ' + failures.join('\n- '))
  const hash = crypto.createHash('sha256').update(source).digest('hex')
  const options = await prettierOptions(root)
  const rendered = [{ file: GENERATED_FILES[0], code: renderGui(config, hash) }]
  const files = []
  for (const entry of rendered) {
    const filePath = path.join(root, entry.file)
    const content = await prettier.format(entry.code, {
      ...options,
      parser: 'typescript',
      filepath: filePath,
    })
    files.push({ file: entry.file, content })
  }
  return { hash, routes: config.routes.length, files }
}

async function main() {
  try {
    const generated = await generateRoutes(DEFAULT_ROOT)
    for (const file of generated.files) {
      const target = path.join(DEFAULT_ROOT, file.file)
      fs.mkdirSync(path.dirname(target), { recursive: true })
      fs.writeFileSync(target, file.content, 'utf8')
      console.log('gen-routes: wrote ' + file.file)
    }
    console.log(
      'gen-routes: OK · ' + generated.routes + ' routes · sha256 ' + generated.hash.slice(0, 12),
    )
  } catch (error) {
    fail(String(error && error.message ? error.message : error))
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main()
}

import { spawnSync } from 'node:child_process'
import crypto from 'node:crypto'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { afterAll, describe, expect, it } from 'vitest'
import { pkgPath } from '../../../helpers/pkg'

const PACKAGE = pkgPath()
const CHECK = path.join(PACKAGE, 'scripts', 'check-routes.mjs')
const ROUTING = 'config/routing.json'
const GENERATED = ['src/plan/routes.generated.ts', 'runtime/core/dispatcher/routes.generated.ts']
const tmpRoots: string[] = []

function fixture(): string {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'dsh-routes-'))
  tmpRoots.push(root)
  fs.mkdirSync(path.join(root, 'config'), { recursive: true })
  fs.copyFileSync(path.join(PACKAGE, ROUTING), path.join(root, ROUTING))
  fs.copyFileSync(path.join(PACKAGE, '.prettierrc.json'), path.join(root, '.prettierrc.json'))
  for (const file of GENERATED) {
    fs.mkdirSync(path.join(root, path.dirname(file)), { recursive: true })
    fs.copyFileSync(path.join(PACKAGE, file), path.join(root, file))
  }
  return root
}

function check(root: string, extraArgs: string[] = []) {
  const result = spawnSync(process.execPath, [CHECK, '--json', '--root', root, ...extraArgs], {
    cwd: PACKAGE,
    encoding: 'utf8',
  })
  let report: Record<string, unknown> | null
  try {
    report = JSON.parse(result.stdout)
  } catch {
    report = null
  }
  return { status: result.status, stdout: result.stdout, stderr: result.stderr, report }
}

function readRouting(root: string): Record<string, unknown> {
  return JSON.parse(fs.readFileSync(path.join(root, ROUTING), 'utf8')) as Record<string, unknown>
}

function writeRouting(root: string, routing: Record<string, unknown>): void {
  fs.writeFileSync(path.join(root, ROUTING), JSON.stringify(routing, null, 2) + '\n', 'utf8')
}

afterAll(() => {
  for (const root of tmpRoots) fs.rmSync(root, { recursive: true, force: true })
})

describe('generated route tables (D3)', () => {
  it('keeps the checked-in tables fresh against config/routing.json', () => {
    const result = check(PACKAGE)
    expect(result.status).toBe(0)
    expect(result.report?.ok).toBe(true)
    expect(result.report?.routes).toBeGreaterThan(30)
    expect(String(result.report?.source)).toBe(ROUTING)
  })

  it('stamps the source hash into both generated headers', () => {
    const source = fs.readFileSync(path.join(PACKAGE, ROUTING), 'utf8')
    const hash = crypto.createHash('sha256').update(source).digest('hex')
    for (const file of GENERATED) {
      const text = fs.readFileSync(path.join(PACKAGE, file), 'utf8')
      expect(text).toContain('generated by scripts/gen-routes.mjs; do not edit')
      expect(text).toContain('// source-sha256: ' + hash)
    }
  })

  it('fails when a routing row is removed without regenerating', () => {
    const root = fixture()
    const routing = readRouting(root)
    const rows = routing.routes as unknown[]
    expect(rows.length).toBeGreaterThan(1)
    rows.splice(0, 1)
    writeRouting(root, routing)
    const result = check(root)
    expect(result.status).toBe(1)
    expect(result.report?.ok).toBe(false)
    expect(String(result.report?.failures)).toContain('stale')
  })

  it('fails when a generated table is hand-edited', () => {
    const root = fixture()
    fs.appendFileSync(path.join(root, GENERATED[0]), '// hand edit\n', 'utf8')
    const result = check(root)
    expect(result.status).toBe(1)
    expect(String(result.report?.failures)).toContain('stale')
  })

  it('fails when a generated table is missing', () => {
    const root = fixture()
    fs.rmSync(path.join(root, GENERATED[1]))
    const result = check(root)
    expect(result.status).toBe(1)
    expect(String(result.report?.failures)).toContain('is missing')
  })

  it('fails when routing.json violates the schema', () => {
    const root = fixture()
    const routing = readRouting(root)
    const rows = routing.routes as Array<Record<string, unknown>>
    rows[0].kind = 'magic'
    writeRouting(root, routing)
    const result = check(root)
    expect(result.status).toBe(1)
    expect(String(result.report?.failures)).toContain('kind')
  })

  it('rejects unknown CLI arguments with exit 2', () => {
    const result = spawnSync(process.execPath, [CHECK, '--nonsense'], {
      cwd: PACKAGE,
      encoding: 'utf8',
    })
    expect(result.status).toBe(2)
  })
})
